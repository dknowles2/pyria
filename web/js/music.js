export function resolveRegionTheme(regionId, realmId) {
  if (regionId && REGION_THEME_MAP[regionId]) {
    return REGION_THEME_MAP[regionId];
  }
  const idLower = String(regionId || '').toLowerCase();
  if (idLower) {
    if (/vault|sanctum|shrine|throne|citadel/.test(idLower)) return 'vault';
    if (/camp|workshop|market|courtyard|terrace/.test(idLower)) return 'camp';
    if (/stream|river|glade|grove|pool|cistern|spring|marsh|shallows|grotto|lagoon/.test(idLower)) return 'stream';
    if (/valley|meadow|highlands|woods|skyway|starbridge|clouddock/.test(idLower)) return 'meadow';
  }
  const realmLower = String(realmId || '').toLowerCase();
  if (/meadow|woods|shallows|highlands|valley|starbridge|clouddock/.test(realmLower)) {
    return 'meadow';
  }
  if (/market|courtyard|terrace/.test(realmLower)) {
    return 'camp';
  }
  if (/grotto|lighthouse/.test(realmLower)) {
    return 'stream';
  }
  if (/throne|sanctum|citadel|bastion/.test(realmLower)) {
    return 'vault';
  }
  return 'ruins';
}

// MIDI note number -> frequency in Hz
export function midiToFreq(midi) {
  return 440 * Math.pow(2, (midi - 69) / 12);
}

// Note name helper (e.g. "C4", "F#5", "Bb3") -> MIDI number
const NOTE_OFFSETS = {
  C: 0, 'C#': 1, Db: 1,
  D: 2, 'D#': 3, Eb: 3,
  E: 4,
  F: 5, 'F#': 6, Gb: 6,
  G: 7, 'G#': 8, Ab: 8,
  A: 9, 'A#': 10, Bb: 10,
  B: 11,
};

function n(name) {
  if (!name || name === '-') return null;
  const m = name.match(/^([A-G][#b]?)(-?\d)$/);
  if (!m) return null;
  return (parseInt(m[2], 10) + 1) * 12 + NOTE_OFFSETS[m[1]];
}

// Helper to parse a 32-step section definition into MIDI arrays
function parseSection({ lead, counter, bass, bassWalk, arp, pad, padExt }) {
  const mapNotes = (arr) => arr.map(n);
  const mapChords = (arr) => arr.map((ch) => (ch ? ch.map(n) : null));
  return {
    lead: mapNotes(lead),
    counter: counter ? mapNotes(counter) : new Array(32).fill(null),
    bass: mapNotes(bass),
    bassWalk: bassWalk ? mapNotes(bassWalk) : new Array(32).fill(null),
    arp: mapNotes(arp),
    pad: mapChords(pad),
    padExt: padExt ? mapChords(padExt) : mapChords(pad),
  };
}

// Helper to expand 4 bar-chords into a 32-step pad track (chord on step 0, 8, 16, 24)
function barPads(chords) {
  const out = new Array(32).fill(null);
  for (let i = 0; i < 4; i++) {
    out[i * 8] = chords[i] || null;
  }
  return out;
}

