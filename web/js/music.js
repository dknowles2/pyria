function safeGetStorage(key) {
  try {
    if (typeof localStorage !== 'undefined') {
      return localStorage.getItem(key);
    }
  } catch (_) {}
  return null;
}

function safeSetStorage(key, value) {
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(key, value);
    }
  } catch (_) {}
}

export class MusicEngine {
  constructor() {
    const saved = safeGetStorage(MUSIC_ENABLED_KEY);
    this.enabled = saved === null ? true : saved === 'true';
    this.themeName = 'title';
    this.era = '8bit';
    this.ducked = false;

    this.ctx = null;
    this.masterGain = null;
    this.compressor = null;
    this.duckGain = null;
    this.transitionGain = null;
    this.echoDelay = null;
    this.echoFeedback = null;
    this.echoFilter = null;
    this.echoWet = null;
    this.noiseBuffer = null;

    this.timerId = null;
    this.debounceTimerId = null;
    this.crossfadeTimerId = null;
    this.pendingTheme = null;
    this.nextNoteTime = 0;

    // Multi-section playback state
    this.currentStep = 0;      // 0..31 within current section
    this.sectionIndex = 0;     // 0..form.length-1
    this.cycleIndex = 0;       // increments each full 16-bar macro-cycle
    this.unlocked = false;

    this.listeners = new Set();
    this.installGestureUnlock();
  }

  installGestureUnlock() {
    if (typeof window === 'undefined') return;
    const unlock = () => {
      this.unlocked = true;
      window.removeEventListener('pointerdown', unlock, true);
      window.removeEventListener('keydown', unlock, true);
      if (this.enabled) {
        this.start();
      }
    };
    window.addEventListener('pointerdown', unlock, { capture: true, passive: true });
    window.addEventListener('keydown', unlock, { capture: true, passive: true });
  }

  onChange(fn) {
    this.listeners.add(fn);
    return () => this.listeners.delete(fn);
  }

  emitChange() {
    for (const fn of this.listeners) {
      fn(this.enabled);
    }
  }

  isEnabled() {
    return this.enabled;
  }

  resetSongPosition() {
    this.currentStep = 0;
    this.sectionIndex = 0;
    this.cycleIndex = 0;
  }

  ensureContext() {
    if (!this.unlocked) return null;
    if (!this.ctx) {
      const AudioCtx =
        typeof window !== 'undefined' && (window.AudioContext || window.webkitAudioContext);
      if (!AudioCtx) return null;
      this.ctx = new AudioCtx();

      this.transitionGain = this.ctx.createGain();
      this.transitionGain.gain.setValueAtTime(1.0, this.ctx.currentTime);

      this.duckGain = this.ctx.createGain();
      this.duckGain.gain.setValueAtTime(
        this.ducked ? DUCKED_MULTIPLIER : 1.0,
        this.ctx.currentTime
      );

      this.masterGain = this.ctx.createGain();
      this.masterGain.gain.setValueAtTime(MASTER_GAIN, this.ctx.currentTime);

      // Gentle dynamics compressor prevents clipping on lush 32/64-bit orchestral passages
      if (typeof this.ctx.createDynamicsCompressor === 'function') {
        this.compressor = this.ctx.createDynamicsCompressor();
        this.compressor.threshold.setValueAtTime(-16, this.ctx.currentTime);
        this.compressor.knee.setValueAtTime(18, this.ctx.currentTime);
        this.compressor.ratio.setValueAtTime(4, this.ctx.currentTime);
        this.compressor.attack.setValueAtTime(0.008, this.ctx.currentTime);
        this.compressor.release.setValueAtTime(0.18, this.ctx.currentTime);
      }

      // Parallel spatial delay bus (dry in 8-bit, progressively lusher in 16/32/64-bit)
      if (typeof this.ctx.createDelay === 'function') {
        this.echoDelay = this.ctx.createDelay(1.0);
        this.echoDelay.delayTime.setValueAtTime(
          ERA_ECHO_TIME[this.era] || 0.22,
          this.ctx.currentTime
        );
        this.echoFeedback = this.ctx.createGain();
        this.echoFeedback.gain.setValueAtTime(0.28, this.ctx.currentTime);
        this.echoFilter = this.ctx.createBiquadFilter();
        this.echoFilter.type = 'lowpass';
        this.echoFilter.frequency.setValueAtTime(2200, this.ctx.currentTime);
        this.echoWet = this.ctx.createGain();
        this.echoWet.gain.setValueAtTime(
          ERA_ECHO_WET[this.era] ?? 0.0,
          this.ctx.currentTime
        );

        this.transitionGain.connect(this.echoDelay);
        this.echoDelay.connect(this.echoFilter);
        this.echoFilter.connect(this.echoFeedback);
        this.echoFeedback.connect(this.echoDelay);
        this.echoFilter.connect(this.echoWet);
        this.echoWet.connect(this.duckGain);
      }

      // Dry path
      this.transitionGain.connect(this.duckGain);
      if (this.compressor) {
        this.duckGain.connect(this.compressor);
        this.compressor.connect(this.masterGain);
      } else {
        this.duckGain.connect(this.masterGain);
      }
      this.masterGain.connect(this.ctx.destination);

      // White-noise buffer (0.35s) for percussion: hi-hats, snares, and cymbal swells
      const length = Math.floor(this.ctx.sampleRate * 0.35);
      const buffer = this.ctx.createBuffer(1, length, this.ctx.sampleRate);
      const data = buffer.getChannelData(0);
      for (let i = 0; i < length; i++) {
        data[i] = Math.random() * 2 - 1;
      }
      this.noiseBuffer = buffer;
    }
    if (this.ctx.state === 'suspended') {
      this.ctx.resume().catch(() => {});
    }
    return this.ctx;
  }

  start() {
    if (!this.enabled || !this.unlocked) return;
    const ctx = this.ensureContext();
    if (!ctx) return;

    if (this.timerId !== null) return;
    this.nextNoteTime = ctx.currentTime + 0.06;
    this.timerId = setInterval(() => this.scheduler(), SCHEDULER_INTERVAL_MS);
  }

  stop() {
    if (this.timerId !== null) {
      clearInterval(this.timerId);
      this.timerId = null;
    }
    if (this.ctx && this.ctx.state === 'running') {
      this.ctx.suspend().catch(() => {});
    }
  }

  setEnabled(flag) {
    this.enabled = Boolean(flag);
    safeSetStorage(MUSIC_ENABLED_KEY, String(this.enabled));
    if (this.enabled) {
      this.unlocked = true; // Toggling On is itself a user gesture
      this.start();
    } else {
      this.stop();
    }
    this.emitChange();
    return this.enabled;
  }

  toggle() {
    return this.setEnabled(!this.enabled);
  }

  cancelPendingTransition() {
    if (this.debounceTimerId !== null) {
      clearTimeout(this.debounceTimerId);
      this.debounceTimerId = null;
    }
    if (this.crossfadeTimerId !== null) {
      clearTimeout(this.crossfadeTimerId);
      this.crossfadeTimerId = null;
    }
    this.pendingTheme = null;
  }

  setTheme(themeName, { immediate = false } = {}) {
    const resolved = THEMES[themeName] ? themeName : 'title';

    // If we're already on this theme and no transition is in flight, no-op
    if (resolved === this.themeName && !this.pendingTheme) {
      return;
    }

    this.cancelPendingTransition();

    // Immediate switch for screen changes or when audio isn't actively playing
    if (immediate || !this.ctx || !this.transitionGain || !this.enabled || this.timerId === null) {
      this.themeName = resolved;
      this.resetSongPosition();
      if (this.ctx && this.transitionGain) {
        const now = this.ctx.currentTime;
        this.transitionGain.gain.cancelScheduledValues(now);
        this.transitionGain.gain.setValueAtTime(1.0, now);
      }
      return;
    }

    // Debounce rapid region border crossings, then dip -> switch -> ramp back up
    this.pendingTheme = resolved;
    this.debounceTimerId = setTimeout(() => {
      this.debounceTimerId = null;
      const targetTheme = this.pendingTheme;
      if (!targetTheme || targetTheme === this.themeName) {
        this.pendingTheme = null;
        return;
      }
      if (!this.ctx || !this.transitionGain || !this.enabled) {
        this.themeName = targetTheme;
        this.resetSongPosition();
        this.pendingTheme = null;
        return;
      }

      const now = this.ctx.currentTime;
      const fadeOutSec = CROSSFADE_OUT_MS / 1000;
      this.transitionGain.gain.cancelScheduledValues(now);
      this.transitionGain.gain.setValueAtTime(this.transitionGain.gain.value, now);
      this.transitionGain.gain.linearRampToValueAtTime(0.0001, now + fadeOutSec);

      this.crossfadeTimerId = setTimeout(() => {
        this.crossfadeTimerId = null;
        this.themeName = targetTheme;
        this.resetSongPosition();
        this.pendingTheme = null;
        if (this.ctx && this.transitionGain) {
          const t = this.ctx.currentTime;
          this.transitionGain.gain.cancelScheduledValues(t);
          this.transitionGain.gain.setValueAtTime(0.0001, t);
          this.transitionGain.gain.linearRampToValueAtTime(1.0, t + CROSSFADE_IN_SEC);
        }
      }, CROSSFADE_OUT_MS);
    }, REGION_DEBOUNCE_MS);
  }

  setEra(eraKey) {
    if (Object.prototype.hasOwnProperty.call(ERA_LEVELS, eraKey)) {
      this.era = eraKey;
    } else {
      this.era = '8bit';
    }
    this.updateEraFx();
  }

  updateEraFx() {
    if (!this.ctx) return;
    const now = this.ctx.currentTime;
    if (this.echoWet) {
      const targetWet = ERA_ECHO_WET[this.era] ?? 0.0;
      this.echoWet.gain.cancelScheduledValues(now);
      this.echoWet.gain.setValueAtTime(this.echoWet.gain.value, now);
      this.echoWet.gain.linearRampToValueAtTime(targetWet, now + 0.25);
    }
    if (this.echoDelay) {
      const targetDelay = ERA_ECHO_TIME[this.era] || 0.22;
      this.echoDelay.delayTime.setValueAtTime(targetDelay, now);
    }
  }

  setDucked(isDucked) {
    const next = Boolean(isDucked);
    if (this.ducked === next) return;
    this.ducked = next;
    if (!this.ctx || !this.duckGain) return;

    const now = this.ctx.currentTime;
    const target = this.ducked ? DUCKED_MULTIPLIER : 1.0;
    const rampSec = this.ducked ? 0.22 : 0.35;
    this.duckGain.gain.cancelScheduledValues(now);
    this.duckGain.gain.setValueAtTime(this.duckGain.gain.value, now);
    this.duckGain.gain.linearRampToValueAtTime(target, now + rampSec);
  }

  getActiveSection(theme) {
    const form = theme.form || ['A'];
    const key = form[this.sectionIndex % form.length] || 'A';
    return {
      key,
      section: theme.sections[key] || theme.sections.A,
    };
  }

  advanceStep(theme) {
    const form = theme.form || ['A'];
    this.currentStep += 1;
    if (this.currentStep >= 32) {
      this.currentStep = 0;
      this.sectionIndex += 1;
      if (this.sectionIndex >= form.length) {
        this.sectionIndex = 0;
        this.cycleIndex += 1;
      }
    }
  }

  scheduler() {
    if (!this.ctx || !this.enabled) return;
    const theme = THEMES[this.themeName] || THEMES.title;
    const stepDuration = 60 / theme.bpm / 2; // 8th-note steps

    while (this.nextNoteTime < this.ctx.currentTime + LOOKAHEAD_SEC) {
      const { key, section } = this.getActiveSection(theme);
      this.scheduleStep(theme, section, key, this.currentStep, this.cycleIndex, this.nextNoteTime, stepDuration);
      this.nextNoteTime += stepDuration;
      this.advanceStep(theme);
    }
  }

  playVoice({
    freq,
    time,
    duration,
    type,
    volume,
    cutoff = 2200,
    attack = 0.015,
    detune = 0,
    vibratoDepth = 0,
    vibratoRate = 5.2,
  }) {
    const ctx = this.ctx;
    if (!ctx || !this.transitionGain || !freq) return;

    const osc = ctx.createOscillator();
    const filter = ctx.createBiquadFilter();
    const gain = ctx.createGain();

    osc.type = type;
    osc.frequency.setValueAtTime(freq, time);
    if (detune) osc.detune.setValueAtTime(detune, time);

    let lfo = null;
    if (vibratoDepth > 0 && duration >= 0.22) {
      lfo = ctx.createOscillator();
      const lfoGain = ctx.createGain();
      lfo.type = 'sine';
      lfo.frequency.setValueAtTime(vibratoRate, time);
      lfoGain.gain.setValueAtTime(0, time);
      lfoGain.gain.linearRampToValueAtTime(vibratoDepth, time + Math.min(0.14, duration * 0.4));
      lfo.connect(lfoGain);
      lfoGain.connect(osc.detune);
      lfo.start(time);
      lfo.stop(time + duration + 0.04);
    }

    filter.type = 'lowpass';
    filter.frequency.setValueAtTime(cutoff, time);

    const safeAtk = Math.min(attack, duration * 0.45);
    gain.gain.setValueAtTime(0.0001, time);
    gain.gain.linearRampToValueAtTime(volume, time + safeAtk);
    gain.gain.exponentialRampToValueAtTime(0.0001, time + duration);

    osc.connect(filter);
    filter.connect(gain);
    gain.connect(this.transitionGain);

    osc.start(time);
    osc.stop(time + duration + 0.03);
  }

  playKick(time, volume = 0.22, pitchStart = 128, pitchEnd = 42, duration = 0.14) {
    const ctx = this.ctx;
    if (!ctx || !this.transitionGain) return;

    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = 'sine';
    osc.frequency.setValueAtTime(pitchStart, time);
    osc.frequency.exponentialRampToValueAtTime(pitchEnd, time + duration * 0.75);

    gain.gain.setValueAtTime(0.0001, time);
    gain.gain.linearRampToValueAtTime(volume, time + 0.005);
    gain.gain.exponentialRampToValueAtTime(0.0001, time + duration);

    osc.connect(gain);
    gain.connect(this.transitionGain);

    osc.start(time);
    osc.stop(time + duration + 0.02);
  }

  playTimpani(time, midiNote, volume = 0.26) {
    const ctx = this.ctx;
    if (!ctx || !this.transitionGain || !midiNote) return;
    const baseFreq = midiToFreq(midiNote);

    const osc = ctx.createOscillator();
    const filter = ctx.createBiquadFilter();
    const gain = ctx.createGain();

    osc.type = 'triangle';
    osc.frequency.setValueAtTime(baseFreq * 1.12, time);
    osc.frequency.exponentialRampToValueAtTime(baseFreq, time + 0.06);

    filter.type = 'lowpass';
    filter.frequency.setValueAtTime(420, time);

    gain.gain.setValueAtTime(0.0001, time);
    gain.gain.linearRampToValueAtTime(volume, time + 0.008);
    gain.gain.exponentialRampToValueAtTime(0.0001, time + 0.34);

    osc.connect(filter);
    filter.connect(gain);
    gain.connect(this.transitionGain);

    osc.start(time);
    osc.stop(time + 0.37);
  }

  playSnare(time, volume = 0.06, duration = 0.085, toneFreq = 210) {
    const ctx = this.ctx;
    if (!ctx || !this.transitionGain || !this.noiseBuffer) return;

    // Noise burst
    const src = ctx.createBufferSource();
    src.buffer = this.noiseBuffer;

    const filter = ctx.createBiquadFilter();
    filter.type = 'bandpass';
    filter.frequency.setValueAtTime(2400, time);
    filter.Q.setValueAtTime(0.9, time);

    const gain = ctx.createGain();
    gain.gain.setValueAtTime(0.0001, time);
    gain.gain.linearRampToValueAtTime(volume, time + 0.004);
    gain.gain.exponentialRampToValueAtTime(0.0001, time + duration);

    src.connect(filter);
    filter.connect(gain);
    gain.connect(this.transitionGain);

    src.start(time);
    src.stop(time + duration + 0.02);

    // Subtle body thump
    const body = ctx.createOscillator();
    const bodyGain = ctx.createGain();
    body.type = 'triangle';
    body.frequency.setValueAtTime(toneFreq, time);
    body.frequency.exponentialRampToValueAtTime(toneFreq * 0.55, time + 0.055);
    bodyGain.gain.setValueAtTime(0.0001, time);
    bodyGain.gain.linearRampToValueAtTime(volume * 0.55, time + 0.003);
    bodyGain.gain.exponentialRampToValueAtTime(0.0001, time + 0.06);
    body.connect(bodyGain);
    bodyGain.connect(this.transitionGain);
    body.start(time);
    body.stop(time + 0.075);
  }

  playShimmerTick(time, accent, volumeScale = 1.0) {
    const ctx = this.ctx;
    if (!ctx || !this.transitionGain || !this.noiseBuffer) return;

    const src = ctx.createBufferSource();
    src.buffer = this.noiseBuffer;

    const filter = ctx.createBiquadFilter();
    filter.type = 'highpass';
    filter.frequency.setValueAtTime(accent ? 5600 : 6800, time);

    const gain = ctx.createGain();
    const vol = (accent ? 0.044 : 0.022) * volumeScale;
    gain.gain.setValueAtTime(0.0001, time);
    gain.gain.linearRampToValueAtTime(vol, time + 0.004);
    gain.gain.exponentialRampToValueAtTime(0.0001, time + (accent ? 0.045 : 0.032));

    src.connect(filter);
    filter.connect(gain);
    gain.connect(this.transitionGain);

    src.start(time);
    src.stop(time + 0.055);
  }

  playCymbalSwell(time, volume = 0.045) {
    const ctx = this.ctx;
    if (!ctx || !this.transitionGain || !this.noiseBuffer) return;

    const src = ctx.createBufferSource();
    src.buffer = this.noiseBuffer;

    const filter = ctx.createBiquadFilter();
    filter.type = 'highpass';
    filter.frequency.setValueAtTime(4800, time);

    const gain = ctx.createGain();
    gain.gain.setValueAtTime(0.0001, time);
    gain.gain.linearRampToValueAtTime(volume, time + 0.02);
    gain.gain.exponentialRampToValueAtTime(0.0001, time + 0.32);

    src.connect(filter);
    filter.connect(gain);
    gain.connect(this.transitionGain);

    src.start(time);
    src.stop(time + 0.34);
  }

  scheduleStep(theme, section, sectionKey, step, cycleIndex, time, stepDur) {
    const eraLevel = ERA_LEVELS[this.era] ?? 0; // 0: 8bit, 1: 16bit, 2: 32bit, 3: 64bit
    const cycleMode = cycleIndex % 4;
    const isClimax = sectionKey === 'C' || (sectionKey === 'B' && cycleMode === 3);
    const isBridge = sectionKey === 'B';
    const isPhraseEnd = step >= 28;
    const isDownbeat = step % 8 === 0;
    const isBeatAccent = step % 4 === 0;

    // Gentle dynamic breathing across beats and sections
    const accentMult = isDownbeat ? 1.08 : isBeatAccent ? 1.02 : 0.94;
    const sectionMult = sectionKey === 'C' ? 1.07 : sectionKey === 'B' ? 0.97 : 1.0;
    const dyn = accentMult * sectionMult;

    // Cycle-based arrangement breathing (prevents fatigue across long sessions)
    const sparseBreakdown =
      (cycleMode === 1 && isBridge && step < 16) ||
      (cycleMode === 2 && sectionKey === 'A2' && step < 8);
    const octaveLiftLead =
      cycleMode === 1 && sectionKey === 'C' && eraLevel >= 1;
    const counterSpotlight =
      cycleMode === 2 && (sectionKey === 'B' || sectionKey === 'A2');

    const leadNote = section.lead[step];
    const nextLeadNote = step < 31 ? section.lead[step + 1] : null;
    const isHeldLead = leadNote !== null && nextLeadNote === null;
    const counterNote = section.counter[step];
    const bassNote = section.bass[step];
    const bassWalkNote = section.bassWalk[step];
    const arpNote = section.arp[step];
    const padChord = eraLevel >= 2 ? section.padExt[step] : section.pad[step];

    // -------------------------------------------------------------------------
    // 1. LEAD VOICE (progresses from NES square -> SNES dual -> PS1 crystal -> N64 orchestral)
    // -------------------------------------------------------------------------
    if (leadNote !== null) {
      const effectiveMidi = octaveLiftLead && leadNote <= 79 ? leadNote + 12 : leadNote;
      const freq = midiToFreq(effectiveMidi);
      const holdMult = isHeldLead ? 1.35 : 1.0;

      if (eraLevel === 3) {
        // 64-bit N64: Lush orchestral brass/strings + airy octave flute + gentle vibrato on held notes
        const vib = isHeldLead ? 5.5 : 0;
        this.playVoice({
          freq,
          time,
          duration: stepDur * 1.65 * holdMult,
          type: 'sawtooth',
          volume: 0.115 * dyn,
          cutoff: isClimax ? 3000 : 2650,
          attack: 0.028,
          detune: -6,
          vibratoDepth: vib,
        });
        this.playVoice({
          freq,
          time,
          duration: stepDur * 1.65 * holdMult,
          type: 'sawtooth',
          volume: 0.105 * dyn,
          cutoff: isClimax ? 2800 : 2450,
          attack: 0.03,
          detune: 6,
          vibratoDepth: vib,
        });
        this.playVoice({
          freq: freq * 2,
          time,
          duration: stepDur * 1.25 * holdMult,
          type: 'sine',
          volume: (isClimax ? 0.072 : 0.055) * dyn,
          cutoff: 3600,
          attack: 0.035,
          vibratoDepth: vib * 0.7,
        });
      } else if (eraLevel === 2) {
        // 32-bit PS1/GBA: Crystalline layered synth + bell harmonic
        this.playVoice({
          freq,
          time,
          duration: stepDur * 1.5 * holdMult,
          type: 'triangle',
          volume: 0.185 * dyn,
          cutoff: 3200,
          attack: 0.014,
          detune: -4,
        });
        this.playVoice({
          freq,
          time,
          duration: stepDur * 1.45 * holdMult,
          type: 'sawtooth',
          volume: 0.075 * dyn,
          cutoff: 2400,
          attack: 0.018,
          detune: 4,
        });
        this.playVoice({
          freq: freq * 2,
          time,
          duration: stepDur * 0.85,
          type: 'sine',
          volume: 0.072 * dyn,
          cutoff: 3600,
          attack: 0.01,
        });
      } else if (eraLevel === 1) {
        // 16-bit SNES: Warm dual-oscillator detuned lead
        this.playVoice({
          freq,
          time,
          duration: stepDur * 1.45 * holdMult,
          type: 'sawtooth',
          volume: 0.13 * dyn,
          cutoff: 2300,
          attack: 0.02,
          detune: -5,
        });
        this.playVoice({
          freq,
          time,
          duration: stepDur * 1.45 * holdMult,
          type: 'triangle',
          volume: 0.185 * dyn,
          cutoff: 2600,
          attack: 0.02,
          detune: 5,
        });
      } else {
        // 8-bit NES: Crisp warm filtered square lead (slightly shorter pulse feel)
        this.playVoice({
          freq,
          time,
          duration: stepDur * 1.12 * (isHeldLead ? 1.2 : 1.0),
          type: 'square',
          volume: 0.155 * dyn,
          cutoff: 1750,
          attack: 0.009,
        });
      }
    }

    // -------------------------------------------------------------------------
    // 2. COUNTERMELODY / HARMONY VOICE (introduced in 16-bit B/C, richer in 32-bit, full in 64-bit)
    // -------------------------------------------------------------------------
    if (counterNote !== null && eraLevel >= 1) {
      const playCounter =
        (eraLevel === 1 && (sectionKey === 'B' || sectionKey === 'C' || cycleMode >= 2)) ||
        (eraLevel === 2 && (sectionKey !== 'A' || cycleMode >= 1)) ||
        eraLevel === 3;

      if (playCounter) {
        const cFreq = midiToFreq(counterNote);
        const boost = counterSpotlight ? 1.25 : 1.0;
        if (eraLevel === 3) {
          // 64-bit: Warm French horn / woodwind ensemble counterline
          this.playVoice({
            freq: cFreq,
            time,
            duration: stepDur * 1.55,
            type: 'triangle',
            volume: 0.115 * dyn * boost,
            cutoff: 2100,
            attack: 0.025,
            detune: -4,
          });
          this.playVoice({
            freq: cFreq,
            time,
            duration: stepDur * 1.5,
            type: 'sawtooth',
            volume: 0.055 * dyn * boost,
            cutoff: 1700,
            attack: 0.03,
            detune: 5,
          });
        } else if (eraLevel === 2) {
          // 32-bit: Expressive crystalline woodwind/bell counterline
          this.playVoice({
            freq: cFreq,
            time,
            duration: stepDur * 1.35,
            type: 'triangle',
            volume: 0.11 * dyn * boost,
            cutoff: 2500,
            attack: 0.016,
          });
        } else {
          // 16-bit: Gentle SNES harmony echo
          this.playVoice({
            freq: cFreq,
            time,
            duration: stepDur * 1.25,
            type: 'sine',
            volume: 0.095 * dyn * boost,
            cutoff: 1900,
            attack: 0.02,
          });
        }
      }
    }

    // -------------------------------------------------------------------------
    // 3. BASS & WALKING PASSING NOTES (8-bit triangle -> 16-bit + sub -> 32-bit walking -> 64-bit + timpani)
    // -------------------------------------------------------------------------
    const activeBass =
      bassNote !== null
        ? bassNote
        : eraLevel >= 2 && bassWalkNote !== null && !sparseBreakdown
          ? bassWalkNote
          : null;

    if (activeBass !== null) {
      const isPassing = bassNote === null;
      const bFreq = midiToFreq(activeBass);
      const passScale = isPassing ? 0.72 : 1.0;

      if (eraLevel >= 1) {
        this.playVoice({
          freq: bFreq,
          time,
          duration: stepDur * (isPassing ? 1.1 : 1.85),
          type: 'triangle',
          volume: 0.31 * passScale * dyn,
          cutoff: eraLevel === 3 ? 1200 : eraLevel === 2 ? 1050 : 950,
          attack: 0.014,
        });
        this.playVoice({
          freq: bFreq * 0.5,
          time,
          duration: stepDur * (isPassing ? 1.0 : 1.85),
          type: 'sine',
          volume: (eraLevel === 3 ? 0.25 : 0.21) * passScale * dyn,
          cutoff: 520,
          attack: 0.02,
        });
      } else {
        // 8-bit NES triangle bass
        this.playVoice({
          freq: bFreq,
          time,
          duration: stepDur * 1.48,
          type: 'triangle',
          volume: 0.31 * dyn,
          cutoff: 900,
          attack: 0.01,
        });
      }

      // 64-bit Orchestral Timpani on phrase downbeats & turnaround fills
      if (eraLevel === 3 && !isPassing && !sparseBreakdown) {
        if (isDownbeat || (isPhraseEnd && step % 2 === 0 && (isClimax || theme.percStyle === 'heroic'))) {
          this.playTimpani(time, activeBass, isDownbeat ? 0.22 : 0.16);
        }
      }
    }

    // -------------------------------------------------------------------------
    // 4. ARPEGGIO & 16TH-NOTE SUBDIVISIONS (progresses from 8-bit 8th-note -> 32/64-bit 16th-note harp cascades)
    // -------------------------------------------------------------------------
    if (arpNote !== null && !(sparseBreakdown && step % 2 === 1)) {
      const aFreq = midiToFreq(arpNote);
      if (eraLevel === 3) {
        // 64-bit: Lush harp/celesta pluck + 16th-note upper cascade
        this.playVoice({
          freq: aFreq,
          time,
          duration: stepDur * 0.95,
          type: 'triangle',
          volume: 0.095 * dyn,
          cutoff: 3200,
          attack: 0.01,
        });
        if (!sparseBreakdown && (step % 2 === 0 || isPhraseEnd || isClimax)) {
          const nextArp = section.arp[(step + 1) % 32] || arpNote;
          const sparkleMidi = nextArp + 12;
          this.playVoice({
            freq: midiToFreq(sparkleMidi),
            time: time + stepDur * 0.5,
            duration: stepDur * 0.65,
            type: 'sine',
            volume: (isPhraseEnd ? 0.06 : 0.044) * dyn,
            cutoff: 4000,
            attack: 0.008,
          });
        }
      } else if (eraLevel === 2) {
        // 32-bit: Crisp celesta/harp + selective 16th-note ornamentations
        this.playVoice({
          freq: aFreq,
          time,
          duration: stepDur * 0.85,
          type: 'sine',
          volume: 0.105 * dyn,
          cutoff: 2900,
          attack: 0.009,
        });
        if (!sparseBreakdown && (step % 4 === 2 || isPhraseEnd)) {
          const nextArp = section.arp[(step + 1) % 32] || arpNote;
          this.playVoice({
            freq: midiToFreq(nextArp + 12),
            time: time + stepDur * 0.5,
            duration: stepDur * 0.52,
            type: 'sine',
            volume: 0.042 * dyn,
            cutoff: 3400,
            attack: 0.008,
          });
        }
      } else if (eraLevel === 1) {
        // 16-bit: Warm SNES triangle arp
        this.playVoice({
          freq: aFreq,
          time,
          duration: stepDur * 0.85,
          type: 'triangle',
          volume: 0.105 * dyn,
          cutoff: 2500,
          attack: 0.01,
        });
      } else {
        // 8-bit: Classic NES square pulse arp (drops slightly in B for breathing room)
        if (!(isBridge && cycleMode % 2 === 1 && step % 2 === 1)) {
          this.playVoice({
            freq: aFreq,
            time,
            duration: stepDur * 0.62,
            type: 'square',
            volume: 0.062 * dyn,
            cutoff: 1450,
            attack: 0.007,
          });
        }
      }
    }

    // -------------------------------------------------------------------------
    // 5. HARMONIC CHORD PADS (16-bit triads -> 32-bit extended 7th/9th -> 64-bit detuned orchestral strings)
    // -------------------------------------------------------------------------
    if (eraLevel >= 1 && padChord) {
      for (let i = 0; i < padChord.length; i++) {
        const note = padChord[i];
        const pFreq = midiToFreq(note);
        if (eraLevel === 3) {
          // 64-bit: Lush detuned string/choir ensemble swell
          this.playVoice({
            freq: pFreq,
            time,
            duration: stepDur * 7.8,
            type: 'triangle',
            volume: 0.052 * sectionMult,
            cutoff: isClimax ? 2100 : 1850,
            attack: 0.22,
            detune: i % 2 === 0 ? -5 : 5,
          });
          if (i === 0 || i === padChord.length - 1) {
            this.playVoice({
              freq: pFreq,
              time,
              duration: stepDur * 7.6,
              type: 'sine',
              volume: 0.036 * sectionMult,
              cutoff: 1600,
              attack: 0.28,
              detune: i === 0 ? 4 : -4,
            });
          }
        } else if (eraLevel === 2) {
          // 32-bit: Airy extended 4-note synth pad
          this.playVoice({
            freq: pFreq,
            time,
            duration: stepDur * 7.6,
            type: 'sine',
            volume: 0.058 * sectionMult,
            cutoff: 1850,
            attack: 0.19,
          });
        } else {
          // 16-bit: Warm 3-note SNES pad
          this.playVoice({
            freq: pFreq,
            time,
            duration: stepDur * 7.5,
            type: 'sine',
            volume: 0.072 * sectionMult,
            cutoff: 1600,
            attack: 0.18,
          });
        }
      }
    }

    // -------------------------------------------------------------------------
    // 6. PERCUSSION (scales from minimal 8-bit tick -> 16-bit groove -> 32-bit syncopated -> 64-bit orchestral)
    // -------------------------------------------------------------------------
    this.schedulePercussion(theme.percStyle || 'gentle', eraLevel, sectionKey, step, cycleMode, sparseBreakdown, time, stepDur);
  }

  schedulePercussion(style, eraLevel, sectionKey, step, cycleMode, sparseBreakdown, time, stepDur) {
    if (sparseBreakdown && step < 28) return;

    const isFill = step >= 28 && (sectionKey === 'A2' || sectionKey === 'B' || sectionKey === 'C');
    const isHeroic = style === 'heroic';
    const isAdventure = style === 'adventure' || style === 'bouncy';

    // 8-bit: Very light NES noise percussion only on energetic themes
    if (eraLevel === 0) {
      if ((isHeroic || isAdventure) && step % 4 === 2) {
        this.playShimmerTick(time, step % 8 === 6, 0.55);
      }
      return;
    }

    // 16-bit+: Kick drum pattern
    const kickHit =
      step % 8 === 0 ||
      (isHeroic && (step % 8 === 3 || step % 8 === 6)) ||
      (isAdventure && step % 8 === 4 && eraLevel >= 2) ||
      (style === 'mystery' && step % 8 === 0);

    if (kickHit) {
      const kickVol = style === 'gentle' || style === 'shimmer' ? 0.13 : isHeroic ? 0.24 : 0.18;
      this.playKick(time, kickVol * (eraLevel >= 2 ? 1.08 : 0.9));
    }

    // 16-bit+: Hi-hat / shimmer pattern
    if (step % 2 === 1) {
      const hatScale = style === 'mystery' ? 0.65 : style === 'gentle' ? 0.75 : 1.0;
      this.playShimmerTick(time, step % 4 === 3, hatScale);
    }

    // 32-bit+: Crisp snare on backbeats + syncopated 16th-note ghost hats + phrase-end fills
    if (eraLevel >= 2) {
      const snareHit =
        (isHeroic && step % 8 === 4) ||
        (isAdventure && step % 8 === 4) ||
        (style === 'shimmer' && step % 8 === 4 && (sectionKey === 'B' || sectionKey === 'C')) ||
        (style === 'mystery' && step % 8 === 6);

      if (snareHit) {
        const snareVol = isHeroic ? 0.072 : isAdventure ? 0.055 : 0.04;
        this.playSnare(time, snareVol);
      }

      // Syncopated 16th-note shimmer hat
      if ((isHeroic || isAdventure || style === 'shimmer') && step % 4 === 2) {
        this.playShimmerTick(time + stepDur * 0.5, false, 0.6);
      }

      // End-of-section drum fill
      if (isFill) {
        if (step === 29 || step === 30) {
          this.playSnare(time, 0.048, 0.07, step === 29 ? 240 : 190);
        } else if (step === 31) {
          this.playSnare(time, 0.062, 0.09, 175);
          if (eraLevel === 3) {
            this.playSnare(time + stepDur * 0.5, 0.052, 0.07, 220);
          }
        }
      }
    }

    // 64-bit: Orchestral cymbal swell on major section transitions (start of B and C)
    if (eraLevel === 3 && step === 0 && (sectionKey === 'B' || sectionKey === 'C' || (sectionKey === 'A' && cycleMode > 0))) {
      this.playCymbalSwell(time, sectionKey === 'C' ? 0.052 : 0.038);
    }
  }
}

export const music = new MusicEngine();
